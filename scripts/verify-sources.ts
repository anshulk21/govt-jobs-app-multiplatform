// Usage: npm run verify-sources [-- options]
//
// Opens every source URL, follows redirects and records the result:
//   - sets "verified": true only for sources that answered with HTTP 2xx
//   - records "finalUrl" (after redirects) and "lastVerifiedAt"
//   - writes reports/source-health.md
//
// Options:
//   --only=ssc,upsc      check only these source ids
//   --state=UP           check only one state/UT (use --state=central for central)
//   --unverified         check only sources that are not verified yet
//   --dry-run            print results but don't change any files
//   --concurrency=5      parallel requests (default 5)
import fs from 'node:fs';
import path from 'node:path';
import { STATE_BY_CODE } from '../src/core/constants';
import type { Source } from '../src/core/types';
import { createHostThrottle, fetchWithRetry, mapLimit, type FetchResult } from './lib/http';
import { REPORTS_DIR } from './lib/paths';
import { allSources, isGovDomain, loadSourceFiles, saveSourceFile, validateSourceFiles } from './lib/sources';

interface Args {
  only?: Set<string>;
  state?: string;
  unverified: boolean;
  dryRun: boolean;
  concurrency: number;
}

function parseArgs(argv: string[]): Args {
  const args: Args = { unverified: false, dryRun: false, concurrency: 5 };
  for (const a of argv) {
    const [key, value = ''] = a.replace(/^--/, '').split('=');
    if (key === 'only') args.only = new Set(value.split(',').map((s) => s.trim()).filter(Boolean));
    else if (key === 'state') args.state = value.toUpperCase();
    else if (key === 'unverified') args.unverified = true;
    else if (key === 'dry-run') args.dryRun = true;
    else if (key === 'concurrency') args.concurrency = Math.max(1, Number(value) || 5);
    else {
      console.error(`Unknown option: ${a}`);
      process.exit(2);
    }
  }
  return args;
}

interface Checked {
  source: Source;
  result: FetchResult;
}

const cell = (s: string | number | null | undefined) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const where = (s: Source) => (s.state ? `${s.state}` : 'Central');

function sameUrl(a: string, b: string): boolean {
  const norm = (u: string) => u.replace(/^http:/, 'https:').replace(/\/+$/, '').replace('://www.', '://').toLowerCase();
  return norm(a) === norm(b);
}

function sortKey(s: Source): string {
  return `${s.level === 'central' ? '0' : '1'}-${STATE_BY_CODE.get(s.state ?? '')?.name ?? ''}-${s.id}`;
}

function buildReport(checked: Checked[], todo: Source[], all: Source[], partial: boolean): string {
  const ok = checked.filter((c) => c.result.ok);
  const failed = checked.filter((c) => !c.result.ok);
  const tls = ok.filter((c) => c.result.tlsWarning);
  const redirected = ok.filter((c) => c.result.finalUrl && !sameUrl(c.result.finalUrl, c.source.url));
  const nonGov = all.filter((s) => s.url && !isGovDomain(s.url));
  const lines: string[] = [];
  const by = (a: Checked, b: Checked) => sortKey(a.source).localeCompare(sortKey(b.source));

  lines.push('# Source health report', '');
  lines.push(`Generated by \`npm run verify-sources\` on ${new Date().toISOString()}.`);
  if (partial) lines.push('', '> Partial run (filters were used) — only the checked sources are listed below.');
  lines.push('');
  lines.push('| | Count |', '|---|---|');
  lines.push(`| ✅ Working | ${ok.length} |`);
  lines.push(`| ❌ Failing | ${failed.length} |`);
  lines.push(`| ⚠️ Working, but certificate problem | ${tls.length} |`);
  lines.push(`| ↪️ Redirected to a different URL | ${redirected.length} |`);
  lines.push(`| 📝 TODO (no URL yet) | ${todo.length} |`);
  lines.push('');

  if (failed.length) {
    lines.push('## ❌ Failing — fix or disable these', '');
    lines.push('Some Indian government sites block cloud/foreign IPs or are slow. If a site opens fine in your browser, it may still work for the monitor when run from your own PC (see README).', '');
    lines.push('| Where | ID | Name | URL | Error |', '|---|---|---|---|---|');
    for (const c of failed.sort(by)) {
      lines.push(`| ${where(c.source)} | \`${c.source.id}\` | ${cell(c.source.name)} | ${cell(c.source.url)} | ${cell(c.result.error)} |`);
    }
    lines.push('');
  }

  if (redirected.length) {
    lines.push('## ↪️ Redirected — consider updating `url` to the final URL', '');
    lines.push('| Where | ID | URL | Final URL |', '|---|---|---|---|');
    for (const c of redirected.sort(by)) {
      lines.push(`| ${where(c.source)} | \`${c.source.id}\` | ${cell(c.source.url)} | ${cell(c.result.finalUrl)} |`);
    }
    lines.push('');
  }

  if (tls.length) {
    lines.push('## ⚠️ Certificate problems', '');
    lines.push('These sites only loaded after ignoring an HTTPS certificate error (usually a misconfigured certificate chain on the government server). They are marked verified; nothing for you to do.', '');
    for (const c of tls.sort(by)) lines.push(`- \`${c.source.id}\` — ${cell(c.source.url)} (${cell(c.result.error ?? 'certificate error')})`);
    lines.push('');
  }

  if (nonGov.length) {
    lines.push('## 🔎 Not .gov.in / .nic.in — confirm these are official', '');
    lines.push('These use other domains that are believed to be official. Open each once and confirm it is linked from a .gov.in / .nic.in page before trusting it.', '');
    for (const s of [...nonGov].sort((a, b) => sortKey(a).localeCompare(sortKey(b)))) lines.push(`- \`${s.id}\` (${where(s)}) — ${s.url}`);
    lines.push('');
  }

  if (todo.length) {
    lines.push('## 📝 TODO — no URL yet', '');
    lines.push('Find the official site, put it in `url`, set `"enabled": true`, then run `npm run verify-sources -- --only=<id>`.', '');
    for (const s of [...todo].sort((a, b) => sortKey(a).localeCompare(sortKey(b)))) lines.push(`- \`${s.id}\` (${where(s)}) — ${s.name}`);
    lines.push('');
  }

  lines.push('## All checked sources', '');
  lines.push('| Status | Where | ID | Name | HTTP | Time | Final URL |', '|---|---|---|---|---|---|---|');
  for (const c of [...checked].sort(by)) {
    const status = c.result.ok ? (c.result.tlsWarning ? '⚠️' : '✅') : '❌';
    lines.push(
      `| ${status} | ${where(c.source)} | \`${c.source.id}\` | ${cell(c.source.name)} | ${c.result.status ?? '—'} | ${(c.result.ms / 1000).toFixed(1)}s | ${cell(c.result.finalUrl ?? c.result.error)} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const files = loadSourceFiles();
  const errors = validateSourceFiles(files);
  if (errors.length) {
    console.error('Source files have problems. Fix them first (npm run validate-sources):');
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }

  const all = allSources(files);
  const selected = all.filter((s) => {
    if (args.only && !args.only.has(s.id)) return false;
    if (args.state && (s.state ?? 'CENTRAL') !== args.state) return false;
    if (args.unverified && s.verified) return false;
    return true;
  });
  if (args.only) {
    const unknown = [...args.only].filter((id) => !all.some((s) => s.id === id));
    if (unknown.length) console.warn(`Unknown source id(s): ${unknown.join(', ')}`);
  }
  const toCheck = selected.filter((s) => s.url);
  const todo = selected.filter((s) => !s.url);

  console.log(`Checking ${toCheck.length} source(s) with concurrency ${args.concurrency}… (${todo.length} have no URL yet)`);
  const throttle = createHostThrottle();
  let done = 0;
  const checked = await mapLimit(toCheck, args.concurrency, async (source): Promise<Checked> => {
    await throttle(source.url);
    const result = await fetchWithRetry(source.url);
    done++;
    const mark = result.ok ? (result.tlsWarning ? '⚠' : '✓') : '✗';
    console.log(`[${done}/${toCheck.length}] ${mark} ${source.id.padEnd(24)} ${result.status ?? ''} ${result.ok ? '' : result.error ?? ''}`);
    return { source, result };
  });

  const now = new Date().toISOString();
  if (!args.dryRun) {
    const byId = new Map(checked.map((c) => [c.source.id, c.result]));
    for (const f of files) {
      let changed = false;
      for (const s of f.data.sources) {
        const r = byId.get(s.id);
        if (!r) continue;
        s.verified = r.ok;
        if (r.ok && r.finalUrl) s.finalUrl = r.finalUrl;
        s.lastVerifiedAt = now;
        changed = true;
      }
      if (changed) saveSourceFile(f);
    }
    fs.mkdirSync(REPORTS_DIR, { recursive: true });
    const partial = Boolean(args.only || args.state || args.unverified);
    fs.writeFileSync(path.join(REPORTS_DIR, 'source-health.md'), buildReport(checked, todo, all, partial));
  }

  const ok = checked.filter((c) => c.result.ok).length;
  console.log(`\nDone: ${ok} working, ${checked.length - ok} failing, ${todo.length} TODO.`);
  console.log(args.dryRun ? '(dry run — no files changed)' : 'Report written to reports/source-health.md');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
